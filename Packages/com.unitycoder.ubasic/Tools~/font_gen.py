missing = [chr(c) for c in range(32, 127) if chr(c) not in G]
assert not missing, f"missing glyphs: {missing}"

def pack(rows):
    """Row -> byte, bit 7 = leftmost column."""
    out = []
    for r in rows:
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= (0x80 >> i)
        out.append(b)
    return out

# ---- Emit C# ----
lines = []
lines.append("// AUTO-GENERATED by Tools~/font_gen.py -- do not edit by hand.")
lines.append("namespace Unitycoder.UBasic {")
lines.append("    /// <summary>6x8 bitmap font covering printable ASCII 32..126.")
lines.append("    /// One byte per row, bit 7 = leftmost pixel. 8 bytes per glyph.</summary>")
lines.append("    public static class Font6x8 {")
lines.append("        public const int CellW = 6;")
lines.append("        public const int CellH = 8;")
lines.append("        public const int First = 32;")
lines.append("        public const int Last  = 126;")
lines.append("")
lines.append("        public static readonly byte[] Glyphs = {")
for c in range(32, 127):
    ch = chr(c)
    b = pack(G[ch])
    hexs = ", ".join(f"0x{v:02X}" for v in b)
    label = "space" if ch == ' ' else ch
    lines.append(f"            {hexs}, // {c} '{label}'")
lines.append("        };")
lines.append("    }")
lines.append("}")

os.makedirs(OUT_DIR, exist_ok=True)
cs_path = os.path.join(OUT_DIR, "Font6x8.cs")
with open(cs_path, "w") as f:
    f.write("\n".join(lines) + "\n")

# ---- Preview PNG (pure-python PNG writer, no deps) ----
SCALE = 3
COLS = 16
ROWS = (95 + COLS - 1) // COLS
W = COLS * 8 * SCALE
H = ROWS * 10 * SCALE
buf = [[0] * W for _ in range(H)]

for idx in range(95):
    ch = chr(32 + idx)
    gx = (idx % COLS) * 8
    gy = (idx // COLS) * 10
    for ry, row in enumerate(G[ch]):
        for rx, cch in enumerate(row):
            if cch == '#':
                for sy in range(SCALE):
                    for sx in range(SCALE):
                        buf[(gy + ry) * SCALE + sy][(gx + rx) * SCALE + sx] = 255

raw = b"".join(b"\x00" + bytes(row) for row in buf)
def chunk(t, d):
    c = t + d
    return struct.pack(">I", len(d)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)
png = (b"\x89PNG\r\n\x1a\n"
       + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 0))
       + chunk(b"IDAT", zlib.compress(raw, 9))
       + chunk(b"IEND", b""))
png_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_preview.png")
open(png_path, "wb").write(png)
print(f"OK: 95 glyphs -> {cs_path}, preview {W}x{H} -> {png_path}")
